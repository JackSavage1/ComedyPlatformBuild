package com.comedyplatform.mictracker.core.demo

import com.comedyplatform.mictracker.core.json.CoreJson
import com.comedyplatform.mictracker.core.json.JsonValues
import com.comedyplatform.mictracker.core.rules.DateRules
import com.comedyplatform.mictracker.core.rules.Weekdays
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import java.time.DayOfWeek
import java.time.LocalDate
import java.time.LocalDateTime
import java.time.LocalTime
import java.time.format.DateTimeFormatter
import java.time.temporal.TemporalAdjusters
import java.util.Locale

// =============================================================================
// Demo mode data (spec 8.2).
//
// The bundled file (android/app/src/main/assets/demo_data.json, generated by
// scripts/build_demo_data.py) stores dates RELATIVE to today — e.g. a set has
// "weeks_ago": 2 instead of a date — so the demo always looks current. This
// file turns those helper keys into real dates for a given "today".
// =============================================================================

/**
 * The date rules of spec 8.2. "Today" is passed in (the device's local date)
 * so the rules are easy to test.
 */
object DemoDates {

    /**
     * Sets and past plans: the mic's most recent [weekday] STRICTLY before
     * [today], minus 7 × [weeksAgo] days. (On a Tuesday, a Tuesday mic's
     * most recent date is last week's Tuesday, not today.)
     */
    fun pastDate(weekday: DayOfWeek, today: LocalDate, weeksAgo: Int): LocalDate =
        today.with(TemporalAdjusters.previous(weekday)).minusWeeks(weeksAgo.toLong())

    /** Upcoming plans: the mic's next [weekday] on or after [today] (rule 16), plus 7 × [weeksAhead] days. */
    fun upcomingDate(weekday: DayOfWeek, today: LocalDate, weeksAhead: Int): LocalDate =
        DateRules.nextOccurrence(weekday, today).plusWeeks(weeksAhead.toLong())

    private val timestampFormat = DateTimeFormatter.ofPattern("yyyy-MM-dd'T'HH:mm:ss", Locale.US)

    /**
     * scrape_log: today minus [daysAgo] at [hour]:[minute] local time, as a
     * Postgres-style timestamp without a zone, e.g. "2026-10-19T14:07:00".
     * Out-of-range hours/minutes are clamped (23:59 at most).
     */
    fun scrapeTimestamp(today: LocalDate, daysAgo: Int, hour: Int, minute: Int): String {
        val time = LocalTime.of(hour.coerceIn(0, 23), minute.coerceIn(0, 59))
        return LocalDateTime.of(today.minusDays(daysAgo.toLong()), time).format(timestampFormat)
    }
}

/**
 * The demo tables after date resolution: plain database rows (same column
 * names as Supabase), ready for [DemoDatabase].
 */
data class DemoTables(
    val mics: List<JsonObject> = emptyList(),
    val sets: List<JsonObject> = emptyList(),
    val plans: List<JsonObject> = emptyList(),
    val scrapedMics: List<JsonObject> = emptyList(),
    val scrapeLog: List<JsonObject> = emptyList(),
)

/** Reads the bundled demo file and resolves its relative dates (spec 8.2). */
object DemoData {

    /** Keys that only exist to describe dates; dropped once a row is resolved. */
    val HELPER_KEYS: Set<String> = setOf("weeks_ago", "weeks_ahead", "when", "days_ago", "hour", "minute")

    /** Parses [jsonText] (the whole demo file) and resolves it for [today]. Throws on invalid JSON. */
    fun resolve(jsonText: String, today: LocalDate): DemoTables {
        val root = CoreJson.json.parseToJsonElement(jsonText) as? JsonObject
            ?: throw IllegalArgumentException("The demo data must be a JSON object.")
        return resolve(root, today)
    }

    /**
     * Resolves every table of [root] for [today]:
     *   - `sets[]` with `weeks_ago` → `date_performed` (past rule)
     *   - `plans[]` → `plan_date` ("when": "upcoming" → upcoming rule, else past rule)
     *   - `scrape_log[]` with `days_ago`/`hour`/`minute` → `last_scraped`
     * A set or plan whose mic (or the mic's weekday) is unknown can't get a
     * date and is left out. Rows that aren't JSON objects are skipped.
     */
    fun resolve(root: JsonObject, today: LocalDate): DemoTables {
        val mics = rows(root["mics"])
        // mic id → the weekday it happens on, for the date rules.
        val micWeekdays: Map<Int, DayOfWeek> = mics.mapNotNull { mic ->
            val id = JsonValues.int(mic["id"]) ?: return@mapNotNull null
            val weekday = Weekdays.parse(JsonValues.text(mic["day_of_week"])) ?: return@mapNotNull null
            id to weekday
        }.toMap()

        fun weekdayOf(row: JsonObject): DayOfWeek? = JsonValues.int(row["open_mic_id"])?.let { micWeekdays[it] }

        val sets = rows(root["sets"]).mapNotNull { row ->
            if ("weeks_ago" !in row) return@mapNotNull withoutHelpers(row)
            val weekday = weekdayOf(row) ?: return@mapNotNull null
            val date = DemoDates.pastDate(weekday, today, intOf(row, "weeks_ago"))
            withoutHelpers(row, "date_performed" to JsonPrimitive(date.toString()))
        }

        val plans = rows(root["plans"]).mapNotNull { row ->
            val whenText = JsonValues.text(row["when"])?.lowercase()
            val date = when {
                whenText == "upcoming" -> weekdayOf(row)?.let { DemoDates.upcomingDate(it, today, intOf(row, "weeks_ahead")) }
                whenText == "past" || "weeks_ago" in row -> weekdayOf(row)?.let { DemoDates.pastDate(it, today, intOf(row, "weeks_ago")) }
                else -> return@mapNotNull withoutHelpers(row) // already has a real plan_date
            } ?: return@mapNotNull null
            withoutHelpers(row, "plan_date" to JsonPrimitive(date.toString()))
        }

        val scrapeLog = rows(root["scrape_log"]).map { row ->
            if (HELPER_KEYS.none { it in row }) return@map row
            val timestamp = DemoDates.scrapeTimestamp(
                today = today,
                daysAgo = intOf(row, "days_ago"),
                hour = intOf(row, "hour"),
                minute = intOf(row, "minute"),
            )
            withoutHelpers(row, "last_scraped" to JsonPrimitive(timestamp))
        }

        return DemoTables(
            mics = mics.map { withoutHelpers(it) },
            sets = sets,
            plans = plans,
            scrapedMics = rows(root["scraped_mics"]).map { withoutHelpers(it) },
            scrapeLog = scrapeLog,
        )
    }

    /** The objects of a JSON array (anything else → empty). */
    private fun rows(element: JsonElement?): List<JsonObject> = JsonValues.array(element).filterIsInstance<JsonObject>()

    /** A helper key as a whole number; missing / junk → 0. */
    private fun intOf(row: JsonObject, key: String): Int = JsonValues.int(row[key]) ?: 0

    /** [row] minus the helper keys, plus [extra] columns. */
    private fun withoutHelpers(row: JsonObject, vararg extra: Pair<String, JsonElement>): JsonObject =
        JsonObject(row.filterKeys { it !in HELPER_KEYS } + extra)
}
