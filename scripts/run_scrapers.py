#!/usr/bin/env python3
"""
Nightly Scraper Job — fills the "Import from Scrapers" queue for the phone apps

The Streamlit Settings page scrapes Bad Slava and FireMics when you click a
button. The phone apps can't run Python, so this script does the same work
headlessly, once a night, on GitHub Actions (.github/workflows/scrape.yml):

    1. scrape each source (badslava, firemics) with the existing scrapers
    2. drop mics that are already in open_mics (the scrapers' own
       compare_*_with_database functions)
    3. put each remaining mic in the `scraped_mics` review queue, where the
       phone's Manage > Import screen shows it with Add / Dismiss buttons
    4. write one scrape_log row per source (shown under Scrape History)
    5. fix known venue coordinates and geocode mics that have no lat/lon

One source failing never stops the other. The exit code is non-zero only
when EVERY source failed, so a single flaky site doesn't turn CI red.

A mic you already Added or Dismissed is never put back in the queue: the
UNIQUE (source, name, venue, day_of_week) constraint catches the repeat and
we only bump its updated_at ("still listed as of tonight").

Usage (from the repo root):
    python scripts/run_scrapers.py            # the real nightly run
    python scripts/run_scrapers.py --dry-run  # scrape + print, write nothing

Database settings come from .streamlit/secrets.toml when it exists,
otherwise from the SUPABASE_DB_* environment variables (see
utils/database.py get_connection()). --dry-run never writes; it reads the
active mic list if it can (to filter out mics you already have) and falls
back to an empty list when no database is reachable.
"""

import argparse
import math
import os
import sys
import warnings
from datetime import date, datetime

# ---------------------------------------------------------------------------
# Make "from utils... / from scrapers..." work when this file is run as
# `python scripts/run_scrapers.py`. Python only puts the SCRIPT'S folder
# (scripts/) on the import path, so we add the repo root ourselves.
# ---------------------------------------------------------------------------
REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if REPO_ROOT not in sys.path:
    sys.path.insert(0, REPO_ROOT)

import pandas as pd  # noqa: E402  (must come after the sys.path tweak)
import psycopg2.extras  # noqa: E402

from scrapers.badslava import scrape_badslava, compare_badslava_with_database  # noqa: E402
from scrapers.firemics import scrape_firemics, compare_firemics_with_database  # noqa: E402
from utils.database import (  # noqa: E402
    BOOLEAN_COLUMNS,
    _to_bool,
    fix_known_venue_coordinates,
    geocode_all_mics,
    get_all_mics,
    get_connection,
    log_scrape,
)

# pandas warns that it "only supports SQLAlchemy" connections every time
# get_all_mics() runs. It works fine with psycopg2, so keep the log clean.
warnings.filterwarnings("ignore", message=".*pandas only supports SQLAlchemy.*")


# Each source: (name stored in scraped_mics.source / scrape_log.source,
#               scrape function, compare function)
SOURCES = [
    ("badslava", scrape_badslava, compare_badslava_with_database),
    ("firemics", scrape_firemics, compare_firemics_with_database),
]

# Keep this identical to the CREATE TABLE in
# supabase/migrations/20261020000000_mobile_api.sql. It's repeated here so
# the job also works on a database where that migration hasn't run yet.
SCRAPED_MICS_DDL = """
    CREATE TABLE IF NOT EXISTS public.scraped_mics (
        id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        source         TEXT NOT NULL,
        name           TEXT NOT NULL,
        venue          TEXT NOT NULL,
        day_of_week    TEXT NOT NULL,
        address        TEXT,
        display_time   TEXT,
        start_time     TEXT,
        cost           TEXT,
        signup_url     TEXT,
        payload        JSONB NOT NULL DEFAULT '{}'::jsonb,
        status         TEXT NOT NULL DEFAULT 'pending'
                       CHECK (status IN ('pending', 'added', 'dismissed')),
        first_seen_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
        updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
        CONSTRAINT scraped_mics_source_name_venue_day_key
            UNIQUE (source, name, venue, day_of_week)
    )
"""

# Insert a new queue row. If (source, name, venue, day_of_week) is already
# there, ONLY touch updated_at — never change status, so an 'added' or
# 'dismissed' mic stays that way.
#
# RETURNING (xmax = 0) is a Postgres trick: xmax is 0 for a row this
# statement freshly inserted and non-zero for one it updated, so it tells
# us "new" vs "already queued".
UPSERT_SQL = """
    INSERT INTO public.scraped_mics
        (source, name, venue, day_of_week, address, display_time,
         start_time, cost, signup_url, payload)
    VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
    ON CONFLICT (source, name, venue, day_of_week)
    DO UPDATE SET updated_at = now()
    RETURNING (xmax = 0) AS inserted, status
"""

# The scrape_log "notes" column is free text; keep it readable.
MAX_ERRORS_IN_NOTES = 5


# ===========================================================================
# PAYLOAD HELPERS — pure functions (no database), easy to test
# ===========================================================================

def _json_safe(value):
    """
    Converts one value into something json.dumps() accepts.

    The scrapers return plain dicts of str/int/bool/None, but we guard
    against the odd float NaN (not valid JSON), dates, and anything else.
    """
    if isinstance(value, str):
        # Postgres text/jsonb can't store the NUL character.
        return value.replace("\x00", "")
    if value is None or isinstance(value, (bool, int)):
        return value
    if isinstance(value, float):
        return value if math.isfinite(value) else None
    if isinstance(value, (datetime, date)):
        return value.isoformat()
    if isinstance(value, dict):
        return {str(k): _json_safe(v) for k, v in value.items()}
    if isinstance(value, (list, tuple, set)):
        return [_json_safe(v) for v in value]
    return str(value)


def normalize_payload(mic):
    """
    Returns a JSON-ready copy of a scraped mic dict for scraped_mics.payload.

    Boolean open_mics columns (is_biweekly, is_active) become real
    true/false — the same coercion utils/database.py applies before an
    insert — so import_scraped_mic() on the database side gets clean data.
    Every other key (including scraper extras like "source") is kept as-is.
    """
    payload = {}
    for key, value in mic.items():
        key = str(key)
        if key in BOOLEAN_COLUMNS:
            # NaN means "missing" here; _to_bool(NaN) would say True.
            if isinstance(value, float) and not math.isfinite(value):
                value = None
            value = _to_bool(value)
        payload[key] = _json_safe(value)
    return payload


def _text_or_none(value):
    """Trimmed text, or None when the value is missing or blank."""
    if value is None:
        return None
    if isinstance(value, float) and not math.isfinite(value):
        return None
    text = str(value).replace("\x00", "").strip()
    return text or None


def queue_row_values(source, mic):
    """
    Builds the parameter tuple for UPSERT_SQL from one scraped mic.

    name / venue / day_of_week are NOT NULL in scraped_mics (the UNIQUE
    constraint ignores NULLs, so a NULL there would let duplicates in);
    a missing value is stored as an empty string instead.
    """
    return (
        source,
        _text_or_none(mic.get("name")) or "",
        _text_or_none(mic.get("venue")) or "",
        _text_or_none(mic.get("day_of_week")) or "",
        _text_or_none(mic.get("address")),
        _text_or_none(mic.get("display_time")),
        _text_or_none(mic.get("start_time")),
        _text_or_none(mic.get("cost")),
        _text_or_none(mic.get("signup_url")),
        psycopg2.extras.Json(normalize_payload(mic)),
    )


def describe_mic(mic):
    """One-line summary used in the log output."""
    when = mic.get("display_time") or mic.get("start_time") or "?"
    cost = mic.get("cost") or "cost?"
    return (
        f"{mic.get('day_of_week', '?')} — {mic.get('name', '?')} "
        f"@ {mic.get('venue', '?')} ({when}, {cost})"
    )


# ===========================================================================
# DATABASE HELPERS
# ===========================================================================

def ensure_scraped_mics_table(conn):
    """
    Creates scraped_mics if it doesn't exist yet (first run before the
    migration). We also switch Row Level Security on for a table we create:
    with no policies that blocks the public API completely, while this job
    (connected as the table owner) is unaffected. The migration later adds
    the admin policy for the phone apps.
    """
    with conn.cursor() as cur:
        cur.execute("SELECT to_regclass('public.scraped_mics')")
        already_there = cur.fetchone()[0] is not None
        if not already_there:
            cur.execute(SCRAPED_MICS_DDL)
            cur.execute(
                "CREATE INDEX IF NOT EXISTS scraped_mics_status_idx "
                "ON public.scraped_mics (status)"
            )
            cur.execute("ALTER TABLE public.scraped_mics ENABLE ROW LEVEL SECURITY")
            print("Created table scraped_mics.", flush=True)
    conn.commit()


def queue_new_mics(conn, source, mics):
    """
    Upserts each mic into scraped_mics and commits.

    Returns a dict of counts:
        queued      — brand-new rows now waiting for review
        refreshed   — already pending; just bumped updated_at
        reviewed    — already added/dismissed earlier; left alone
    """
    counts = {"queued": 0, "refreshed": 0, "reviewed": 0}
    try:
        with conn.cursor() as cur:
            for mic in mics:
                cur.execute(UPSERT_SQL, queue_row_values(source, mic))
                inserted, status = cur.fetchone()
                if inserted:
                    counts["queued"] += 1
                elif status == "pending":
                    counts["refreshed"] += 1
                else:
                    counts["reviewed"] += 1
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    return counts


def _empty_mics_frame():
    """Stand-in for get_all_mics() when no database is reachable (dry run)."""
    return pd.DataFrame(columns=["name", "venue", "day_of_week", "start_time", "address"])


def nulls_as_none(df):
    """
    Returns a copy of the DataFrame where every missing value is None.

    pandas 3 stores a NULL text column value as NaN (a float), and NaN is
    "truthy", so the scrapers' compare functions would try `NaN[:10]` on a
    mic with no address and crash. Converting to plain Python objects with
    None for missing values gives them what they expect.
    """
    as_objects = df.astype(object)
    return as_objects.where(pd.notna(as_objects), None)


# ===========================================================================
# OUTPUT HELPERS — GitHub Actions turns "::error::" lines into annotations
# ===========================================================================

IN_GITHUB_ACTIONS = os.environ.get("GITHUB_ACTIONS") == "true"


def warn(message):
    prefix = "::warning::" if IN_GITHUB_ACTIONS else "WARNING: "
    print(f"{prefix}{message}", flush=True)


def error(message):
    prefix = "::error::" if IN_GITHUB_ACTIONS else "ERROR: "
    print(f"{prefix}{message}", flush=True)


def _join_errors(errors):
    shown = [str(e) for e in errors[:MAX_ERRORS_IN_NOTES]]
    extra = len(errors) - len(shown)
    text = "; ".join(shown)
    if extra > 0:
        text += f"; (+{extra} more)"
    return text


# ===========================================================================
# ONE SOURCE
# ===========================================================================

def run_source(source, scrape_fn, compare_fn, existing_mics, conn, dry_run):
    """
    Scrapes one source, queues its new mics, and logs the run.
    Returns True on success. Never raises — a failure here must not stop
    the next source.
    """
    print(f"\n=== {source} ===", flush=True)
    status = "error"
    notes = ""

    try:
        result = scrape_fn()
        mics = result.get("mics") or []
        errors = result.get("errors") or []

        if not mics:
            # Zero mics almost always means the site changed or was down.
            notes = _join_errors(errors) if errors else "Scraper returned 0 mics."
            error(f"{source}: {notes}")
        else:
            # Some mics parsed, but a few entries may have been skipped.
            for err in errors[:MAX_ERRORS_IN_NOTES]:
                warn(f"{source}: {err}")

            comparison = compare_fn(mics, existing_mics)
            new_mics = comparison.get("new_mics") or []
            matched = comparison.get("matched_mics", 0)
            print(
                f"Found {len(mics)} mics: {matched} already in your database, "
                f"{len(new_mics)} not in it.",
                flush=True,
            )

            if dry_run:
                for mic in new_mics:
                    print(f"  would queue: {describe_mic(mic)}", flush=True)
                counts_text = f"{len(new_mics)} would be queued (dry run)"
            else:
                counts = queue_new_mics(conn, source, new_mics)
                counts_text = (
                    f"{counts['queued']} newly queued, "
                    f"{counts['refreshed']} still pending, "
                    f"{counts['reviewed']} previously reviewed"
                )

            notes = f"{len(mics)} found, {matched} matched, {counts_text}"
            if errors:
                notes += f". {len(errors)} parse warning(s): {_join_errors(errors)}"
            status = "success"
            print(notes, flush=True)

    except Exception as exc:  # noqa: BLE001 — log anything and keep going
        notes = f"{type(exc).__name__}: {exc}"
        error(f"{source}: {notes}")

    if not dry_run:
        try:
            log_scrape(source, status, notes)
        except Exception as exc:  # noqa: BLE001
            warn(f"{source}: could not write scrape_log: {exc}")

    return status == "success"


# ===========================================================================
# MAIN
# ===========================================================================

def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Scrape open mic sites and queue new mics for review."
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Scrape and print what would be queued, without writing to the database.",
    )
    args = parser.parse_args(argv)

    started = datetime.now()
    print(f"Scrape run started {started.isoformat(timespec='seconds')}"
          f"{' (DRY RUN — nothing is written)' if args.dry_run else ''}", flush=True)

    conn = None
    if args.dry_run:
        try:
            existing_mics = get_all_mics()
            print(f"Loaded {len(existing_mics)} active mics to compare against.", flush=True)
        except Exception as exc:  # noqa: BLE001
            warn(f"Couldn't read open_mics ({exc}); comparing against an empty list.")
            existing_mics = _empty_mics_frame()
    else:
        # Without the database there's nothing useful to do — fail loudly.
        try:
            conn = get_connection()
            ensure_scraped_mics_table(conn)
            existing_mics = get_all_mics()
            print(f"Loaded {len(existing_mics)} active mics to compare against.", flush=True)
        except Exception as exc:  # noqa: BLE001
            error(f"Database setup failed: {type(exc).__name__}: {exc}")
            if conn is not None:
                conn.close()
            return 1

    existing_mics = nulls_as_none(existing_mics)

    succeeded = 0
    try:
        for source, scrape_fn, compare_fn in SOURCES:
            if run_source(source, scrape_fn, compare_fn, existing_mics, conn, args.dry_run):
                succeeded += 1
    finally:
        if conn is not None:
            conn.close()

    # Coordinates: same two steps as the Map page's buttons. A failure here
    # is only a warning — the scrape itself already succeeded or failed.
    if not args.dry_run:
        print("\n=== coordinates ===", flush=True)
        try:
            fixed, details = fix_known_venue_coordinates()
            print(f"Known-venue fixes: {fixed} mic(s) updated.", flush=True)
            for line in details:
                print(f"  {line}", flush=True)
        except Exception as exc:  # noqa: BLE001
            warn(f"fix_known_venue_coordinates failed: {exc}")
        try:
            geocoded = geocode_all_mics()
            print(f"Geocoded {geocoded} mic(s).", flush=True)
        except Exception as exc:  # noqa: BLE001
            warn(f"geocode_all_mics failed: {exc}")

    elapsed = (datetime.now() - started).total_seconds()
    print(f"\nDone in {elapsed:.0f}s: {succeeded} of {len(SOURCES)} sources succeeded.", flush=True)

    # Non-zero only when every source failed.
    return 0 if succeeded > 0 else 1


if __name__ == "__main__":
    sys.exit(main())
